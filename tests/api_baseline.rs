//! The public-API baseline.
//!
//! Every `pub` item declared under `src/` is recorded in
//! `docs/api-baseline.txt`. The test fails when the file and the source
//! disagree, which turns a visibility change — a `pub` quietly removed, or an
//! internal type accidentally exposed — into a reviewable diff instead of a
//! silent contract change.
//!
//! The scan is line-level on purpose. `cargo public-api` resolves real paths but
//! needs nightly rustdoc JSON, and this repo pins stable; a coarse check that
//! always runs beats a precise one that nobody runs. Functions produced by macro
//! expansion and the continuation lines of multi-line `pub use` blocks are
//! therefore only partly captured — that is a known, accepted limit.
//!
//! Regenerate after an intentional change:
//!
//! ```text
//! UPDATE_API_BASELINE=1 cargo test --test api_baseline
//! ```

use std::path::{Path, PathBuf};

/// Where the baseline lives.
fn baseline_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("docs/api-baseline.txt")
}

const HEADER: &str = "\
# Charton public-API baseline — generated by tests/api_baseline.rs
# Do not edit. A diff here means the public surface changed; commit it
# together with the change and say why in the PR description.
#
# Format: <file>\\t<item declaration>
";

/// Item kinds the scan records.
const KINDS: &[&str] = &[
    "fn", "struct", "enum", "trait", "type", "static", "mod", "use",
];

/// Modifiers that may sit between `pub` and the item kind.
const MODIFIERS: &[&str] = &["async", "unsafe", "extern", "const", "default"];

/// The declaration if this line declares a public item.
fn public_item(line: &str) -> Option<&str> {
    let trimmed = line.trim_end();
    let rest = trimmed.trim_start().strip_prefix("pub ")?;

    // Skip `pub(crate)`, `pub(super)`: the space after `pub` is required.
    let mut rest = rest;
    loop {
        let (word, tail) = rest.split_once(' ')?;
        if KINDS.contains(&word) {
            return Some(trimmed.trim_start());
        }
        if !MODIFIERS.contains(&word) {
            return None;
        }
        rest = tail.trim_start();
    }
}

/// Every source file under `src/`, in a stable order.
fn sources(root: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(root) else {
        return;
    };
    let mut paths: Vec<PathBuf> = entries
        .filter_map(|entry| entry.ok().map(|e| e.path()))
        .collect();
    paths.sort();

    for path in paths {
        if path.is_dir() {
            sources(&path, out);
        } else if path.extension().is_some_and(|extension| extension == "rs") {
            out.push(path);
        }
    }
}

/// The generated baseline, as the exact bytes of the file.
fn generate() -> String {
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let mut files = Vec::new();
    sources(&manifest.join("src"), &mut files);

    let mut items = Vec::new();
    for file in &files {
        let relative = file
            .strip_prefix(&manifest)
            .unwrap_or(file)
            // Forward slashes on every platform: the baseline is committed and
            // compared as text, so Windows must not produce a different file.
            .to_string_lossy()
            .replace('\\', "/");
        let Ok(text) = std::fs::read_to_string(file) else {
            continue;
        };
        for line in text.lines() {
            if let Some(item) = public_item(line) {
                items.push(format!("{relative}\t{item}"));
            }
        }
    }

    // Byte order, so the file is stable across machines and locales.
    items.sort();

    let mut out = String::from(HEADER);
    for item in items {
        out.push_str(&item);
        out.push('\n');
    }
    out
}

#[test]
fn the_public_api_baseline_matches_the_source() {
    let generated = generate();
    let path = baseline_path();

    if std::env::var_os("UPDATE_API_BASELINE").is_some() {
        std::fs::write(&path, &generated).expect("write the baseline");
        return;
    }

    let committed = std::fs::read_to_string(&path).unwrap_or_else(|error| {
        panic!(
            "cannot read {}: {error}\nGenerate it with: UPDATE_API_BASELINE=1 cargo test --test api_baseline",
            path.display()
        )
    });

    if committed == generated {
        return;
    }

    // Show the lines that were added or removed, not two thousand lines.
    let old: std::collections::BTreeSet<&str> = committed.lines().collect();
    let new: std::collections::BTreeSet<&str> = generated.lines().collect();
    let removed: Vec<&&str> = old.difference(&new).collect();
    let added: Vec<&&str> = new.difference(&old).collect();

    let mut report = String::from("the public API surface changed.\n");
    for line in removed.iter().take(20) {
        report.push_str(&format!("  - {line}\n"));
    }
    for line in added.iter().take(20) {
        report.push_str(&format!("  + {line}\n"));
    }
    report.push_str(
        "\nIf the change was intentional, regenerate and commit the file:\n\
         UPDATE_API_BASELINE=1 cargo test --test api_baseline\n",
    );
    panic!("{report}");
}
